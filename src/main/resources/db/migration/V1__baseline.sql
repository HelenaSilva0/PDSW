-- Schema inicial (anterior a status de usuário e índices adicionais).
-- Bancos já existentes são marcados como V1 via baseline-on-migrate e só executam V2+.
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_telefone UNIQUE (telefone)
);

CREATE TABLE medico (
    id_medico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users (id),
    nome VARCHAR(100) NOT NULL,
    crm VARCHAR(20) NOT NULL UNIQUE,
    especialidade VARCHAR(100) NOT NULL
);

CREATE TABLE paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users (id),
    nome VARCHAR(100) NOT NULL,
    data_nascimento DATE,
    historico_familiar VARCHAR(4000),
    observacoes VARCHAR(4000),
    genero CHAR(1)
);

CREATE TABLE chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id INTEGER NOT NULL REFERENCES medico (id_medico),
    paciente_id INTEGER NOT NULL REFERENCES paciente (id_paciente),
    criado_em TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_chat_paciente ON chat (paciente_id);
CREATE INDEX idx_chat_medico ON chat (medico_id);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chat (id),
    sender VARCHAR(255),
    texto VARCHAR(2000) NOT NULL,
    enviado_em TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE exame (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES paciente (id_paciente),
    descricao VARCHAR(500) NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    nome_armazenado VARCHAR(255) NOT NULL,
    content_type VARCHAR(120),
    tamanho BIGINT,
    versao INTEGER NOT NULL,
    enviado_em TIMESTAMP(6) NOT NULL,
    enviado_por_user_id INTEGER
);

CREATE TABLE historico_familiar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES paciente (id_paciente),
    texto_historico VARCHAR(4000) NOT NULL,
    versao INTEGER NOT NULL,
    criado_em TIMESTAMP(6) NOT NULL,
    criado_por_user_id INTEGER,
    caminhos_exames VARCHAR(2000)
);

CREATE TABLE historico_familiar_anexo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    historico_id BIGINT NOT NULL REFERENCES historico_familiar (id),
    nome_original VARCHAR(255) NOT NULL,
    nome_armazenado VARCHAR(255) NOT NULL,
    content_type VARCHAR(120),
    tamanho BIGINT,
    enviado_em TIMESTAMP(6) NOT NULL,
    enviado_por_user_id INTEGER
);
